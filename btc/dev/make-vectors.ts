/**
 * Writes btc/test-vectors.json: the derivation rule's vectors for every implementation (this package,
 * the Rust facilitator crate x402-chain-bip122, any third-party buyer). Deterministic; rerun with
 *
 *   npm run vectors -w btc
 *
 * The account keys come from the BIP84 test mnemonic ("abandon … about"), so anyone can re-derive them:
 * m/84'/0'/0' gives the design's xpub, m/84'/1'/0' the testnet3 tpub.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { sha256 } from "@noble/hashes/sha2";
import { bytesToHex, hexToBytes, utf8ToBytes } from "@noble/hashes/utils";
import { HDKey } from "@scure/bip32";
import { mnemonicToSeedSync } from "@scure/bip39";
import { derivePaymentAddress, paymentRef, type AddressType } from "../src/derive.js";
import { BTC_MAINNET, BTC_NETWORKS, BTC_TESTNET3, type BtcNetwork } from "../src/networks.js";

export const TEST_MNEMONIC =
  "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about";

function accountXpub(network: BtcNetwork): { path: string; xpub: string } {
  const info = BTC_NETWORKS[network];
  const path = `m/84'/${info.coinType}'/0'`;
  const master = HDKey.fromMasterSeed(mnemonicToSeedSync(TEST_MNEMONIC), info.bip32);
  return { path, xpub: master.derive(path).publicExtendedKey };
}

const PAYMENT_IDS = [
  "00112233445566778899aabbccddeeff",
  "00000000000000000000000000000000",
  "ffffffffffffffffffffffffffffffff",
  "5f0a3c9e1b7d42e8a6c4f2019d8e7b3a",
];

const vectors = [];
for (const network of [BTC_MAINNET, BTC_TESTNET3] as const) {
  const { path, xpub } = accountXpub(network);
  for (const addressType of ["p2wpkh", "p2tr"] as AddressType[]) {
    for (const paymentId of PAYMENT_IDS) {
      const d = derivePaymentAddress(xpub, network, paymentId, addressType);
      vectors.push({
        network,
        accountPath: path,
        payTo: xpub,
        paymentId,
        addressType,
        digest: bytesToHex(sha256(new Uint8Array([...utf8ToBytes("x402-btc"), ...hexToBytes(paymentId)]))),
        indices: d.indices,
        childPath: d.path,
        pubkey: d.pubkey,
        scriptPubKey: d.script,
        address: d.address,
        paymentRef: paymentRef(paymentId),
      });
    }
  }
}

const mainnetXpub = accountXpub(BTC_MAINNET).xpub;
const testnetXpub = accountXpub(BTC_TESTNET3).xpub;
const out = {
  _about:
    "Derivation vectors for the exact scheme on bip122 (docs/specs/scheme_exact_bip122.md). Generated by btc/dev/make-vectors.ts.",
  rule: {
    digest: "d = sha256(utf8(\"x402-btc\") || bytes16(paymentId))",
    indices: "i1 = BE_uint32(d[0..4]) & 0x7fffffff, i2 = BE_uint32(d[4..8]) & 0x7fffffff, i3 = BE_uint32(d[8..12]) & 0x7fffffff",
    child: "non-hardened m/0/i1/i2/i3 below payTo",
    p2wpkh: "0x0014 || hash160(compressed pubkey)",
    p2tr: "BIP86 key-path only: 0x5120 || x(P + int(H_TapTweak(x(P)))·G)",
    paymentRef: "sha256(bytes16(paymentId)), the settler's paymentRef and settledBy value",
  },
  mnemonic: TEST_MNEMONIC,
  vectors,
  rejections: [
    { network: BTC_MAINNET, payTo: testnetXpub, reason: "tpub on Bitcoin mainnet" },
    { network: BTC_TESTNET3, payTo: mainnetXpub, reason: "xpub on Bitcoin testnet3" },
    {
      network: BTC_MAINNET,
      payTo: "zpub6rFR7y4Q2AijBEqTUquhVz398htDFrtymD9xYYfG1m4wAcvPhXNfE3EfH1r1ADqtfSdVCToUG868RvUUkgDKf31mGDtKsAYz2oz2AGutZYs",
      reason: "SLIP-132 zpub (same key as the vector xpub): only xpub/tpub version bytes are accepted",
    },
    { network: BTC_MAINNET, paymentId: "00112233445566778899AABBCCDDEEFF", reason: "uppercase paymentId" },
    { network: BTC_MAINNET, paymentId: "00112233445566778899aabbccddee", reason: "15-byte paymentId" },
  ],
};

const file = join(dirname(fileURLToPath(import.meta.url)), "..", "test-vectors.json");
writeFileSync(file, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${vectors.length} vectors to ${file}`);
